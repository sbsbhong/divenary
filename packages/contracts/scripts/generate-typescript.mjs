import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { compileFromFile } from 'json-schema-to-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageDir = path.resolve(__dirname, '..');
const schemaPath = path.join(packageDir, 'schemas', 'watch-sync-message.schema.json');
const outputPath = path.join(packageDir, 'generated', 'typescript', 'index.ts');

const generated = normalizeWatchSessionType(await compileFromFile(schemaPath, {
  bannerComment: '// This file is auto-generated by json-schema-to-typescript. Do not edit manually.\n',
  cwd: path.join(packageDir, 'schemas'),
  unreachableDefinitions: true
}));

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, 'utf8');

console.log(`Generated TypeScript contracts: ${path.relative(packageDir, outputPath)}`);

function normalizeWatchSessionType(source) {
  const watchSessionPattern =
    /export type WatchSession = \{([\s\S]*?)\} & \(\n[\s\S]*?\n\);\n\nexport interface WatchSyncMessage/;
  const match = source.match(watchSessionPattern);
  if (!match) {
    return source;
  }

  const commonBody = match[1];
  const strictWatchSession = `export interface WatchSessionCommon {${commonBody}}\nexport type WatchSession = WatchSessionCommon & (\n  | { diveMode?: undefined; freedive?: undefined; scuba?: undefined }\n  | { diveMode: "freedive"; freedive: FreeDivePayload; scuba?: never }\n  | { diveMode: "scuba"; scuba: ScubaPayload; freedive?: never }\n);\n\nexport interface WatchSyncMessage`;

  return source
    .replace(watchSessionPattern, strictWatchSession)
    .replaceAll('referenced by `undefined`', 'referenced by `WatchSession`');
}
